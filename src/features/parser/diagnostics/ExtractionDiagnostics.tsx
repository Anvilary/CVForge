'use client'

import { useState } from 'react'
import { isCvForgeGenerated } from '@/lib/parser/cvForgeDetection'
import { readableCoreHeadings } from '@/lib/parser/heuristic/sectionDetection'
import { WorkbenchSectionCard } from '@/shared/components/workbench/WorkbenchSectionCard'
import { type ParserDocument } from '../upload/parserTypes'

export function ExtractionDiagnostics({ document }: { document: ParserDocument | null }) {
  const [isExpanded, setIsExpanded] = useState(true)
  const extraction = document?.extraction
  const isForge = extraction ? isCvForgeGenerated(extraction.metadata) : false
  const signals = extraction?.diagnostics.signals ?? []
  const passedChecks = signals.filter((signal) => signal.status === 'pass').length
  const headings = extraction ? readableCoreHeadings(extraction.text) : []
  const hasSelectableText = Boolean(extraction?.text.trim())

  const status = extraction ? (isForge ? 'CVForge Detected' : 'External PDF') : '-'

  return (
    <WorkbenchSectionCard
      title="Extraction Analysis"
      icon="activity"
      isExpanded={isExpanded}
      onToggle={() => setIsExpanded(!isExpanded)}
      status={status}
    >
      <div className="space-y-4">
        <DiagnosticRow label="File" value={document?.fileName ?? '-'} />
        <DiagnosticRow label="Pages" value={extraction ? String(extraction.pageCount) : '-'} />
        <DiagnosticRow label="Characters" value={extraction ? String(extraction.text.length) : '-'} />
        <DiagnosticRow label="Text extraction checks" value={extraction ? `${passedChecks} of ${signals.length} passed` : '-'} />
        <DiagnosticRow label="Core headings readable" value={extraction ? describeHeadings(headings) : '-'} />
        <DiagnosticRow label="Draft confidence" value={document?.heuristic ? `${document.heuristic.confidence}%` : '-'} />
        
        <div className="pt-2">
          {isForge && (
            <p className="text-[10px] text-ink-3 italic leading-relaxed">
              This PDF was generated by CVForge. If it includes the embedded session attachment, restore uses that structured data instead of a best-effort external parse.
            </p>
          )}
          {extraction && (
            <p className="text-[10px] text-ink-3 italic leading-relaxed">
              Text extraction checks and core headings describe what a text extractor returns. Draft confidence is how much of the document the best-effort parser could map. None of them is a CV quality score or a prediction for any ATS.
            </p>
          )}
          {!extraction && (
            <p className="text-[10px] text-ink-3 italic leading-relaxed">
              Upload a PDF to see results.
            </p>
          )}
        </div>

        {document?.error && (
          <p className="text-xs text-red-200 font-medium" role="alert">
            {document.error}
          </p>
        )}
        {extraction && !hasSelectableText && (
          <p className="text-xs text-amber-200 font-medium" role="alert">
            No selectable text was found. This PDF may be scanned, image-only, or protected.
            Export a text-based PDF and try again; CVForge does not send the file to a cloud OCR service.
          </p>
        )}
        {extraction?.diagnostics.signals.some((signal) => signal.status !== 'pass') && (
          <div className="space-y-2 pt-2" aria-label="Extraction warnings">
            {extraction.diagnostics.signals
              .filter((signal) => signal.status !== 'pass' && signal.id !== 'selectable-text')
              .map((signal) => (
                <div
                  key={signal.id}
                  className="rounded-lg border border-amber-400/15 bg-amber-400/5 p-3"
                >
                  <p className="text-xs font-medium text-amber-100">{signal.label}</p>
                  <p className="mt-1 text-[10px] leading-relaxed text-ink-3">{signal.detected}</p>
                  <p className="mt-1 text-[10px] leading-relaxed text-ink-4">{signal.suggestion}</p>
                </div>
              ))}
          </div>
        )}
      </div>
    </WorkbenchSectionCard>
  )
}

const CORE_HEADING_TOTAL = 3
const HEADING_LABELS: Record<string, string> = { experience: 'Experience', education: 'Education', skills: 'Skills' }

function describeHeadings(found: string[]) {
  const names = found.map((key) => HEADING_LABELS[key] ?? key).join(', ')
  return found.length ? `${found.length} of ${CORE_HEADING_TOTAL} (${names})` : `0 of ${CORE_HEADING_TOTAL}`
}

function DiagnosticRow({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex items-center justify-between gap-16 text-xs">
      <span className="text-ink-4">{label}</span>
      <span className="font-mono text-ink text-right truncate">{value}</span>
    </div>
  )
}
